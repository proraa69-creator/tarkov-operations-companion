import { createRequire } from 'node:module'
import { readFile, writeFile } from 'node:fs/promises'
import { heldLine, manualQuest } from './manualQuests.mjs'
const require = createRequire(import.meta.url)
const source = 'https://raw.githubusercontent.com/tarkovtracker-org/tarkov-data-overlay/main/src/additions/storyChapters.json5'
const OUT = new URL('../src/data/storyQuestIndex.ts', import.meta.url)
const response = await fetch(source, { signal: AbortSignal.timeout(30_000) })
if (!response.ok) throw new Error(`Story index HTTP ${response.status}`)
const chapters = require('json5').parse(await response.text())
const fresh = Object.values(chapters).map(chapter => ({ id: chapter.id, name: chapter.name, order: chapter.order, questId: chapter.chapterQuestId, objectiveQuestIds: [...new Set(chapter.objectives.map(objective => objective.sourceQuestId).filter(Boolean))] }))
// A chapter whose quest was changed by hand (src/data/manualQuests.json; owner, 23.11.2026: «при обновлениях из базы их не трогай»)
// keeps its row as the index has it.
const previous = await readFile(OUT, 'utf8').then(text => JSON.parse(/STORY_QUEST_INDEX = ([\s\S]*) as const/.exec(text)?.[1] ?? '[]')).catch(() => [])
const held = []
const rows = fresh.flatMap(row => {
  if (!manualQuest(row.questId)) return [row]
  const before = previous.find(entry => entry.id === row.id)
  if (JSON.stringify(before) !== JSON.stringify(row)) held.push(row.name)
  return before ? [before] : []
})
for (const before of previous) if (manualQuest(before.questId) && !rows.some(row => row.id === before.id)) { rows.push(before); held.push(before.name) }
if (rows.length < 10 || rows.some(row => !/^[a-z0-9-]+$/.test(row.id) || !/^[a-f0-9]{24}$/.test(row.questId) || row.objectiveQuestIds.some(id => !/^[a-f0-9]{24}$/.test(id)))) throw new Error('Invalid chapter index')
await writeFile(OUT, `// Generated by scripts/update-story-index.mjs from the game-reference chapter index.\n// Source: ${source}\nexport const STORY_QUEST_INDEX = ${JSON.stringify(rows, null, 2)} as const\n`)
console.log(JSON.stringify({ chapterCount: rows.length, chapters: rows.map(row => row.name), objectiveQuestIds: rows.reduce((sum, row) => sum + row.objectiveQuestIds.length, 0) }))
console.log(heldLine(held, 'story chapters'))
