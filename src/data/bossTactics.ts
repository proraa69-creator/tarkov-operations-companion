const byKey = new Map(BOSS_TACTICS.map((entry) => [entry.key, entry]))

/** The app's own boss keys (Gallery, raid card figures) → the tactics key. */
const ALIASES: Record<string, string> = {
  'goon-1': 'birdeye',
  'goon-2': 'knight',
  'goon-3': 'big-pipe',
  'tagilla-2': 'shadow-of-tagilla',
  wadge: 'the-wedge',
  'killa-vengeful': 'shadow-of-tagilla',
}

/** The tactics of a boss by any of the app's keys; undefined for figures without their own (Rogues, Raiders…). */
export function bossTactics(key: string): BossTactics | undefined {
  return byKey.get(ALIASES[key] ?? key)
}

/** The figure / Gallery key of a tactics key (for its picture and maps). */
export function figureKeyOf(tacticsKey: string) {
  return Object.entries(ALIASES).find(([, value]) => value === tacticsKey)?.[0] ?? tacticsKey
}

/** The tactics page of a boss (route /bosses/:key/tactics): opened only from the boss's «Тактика боя» button. */
export const tacticsPath = (key: string) => `/bosses/${encodeURIComponent(ALIASES[key] ?? key)}/tactics`
