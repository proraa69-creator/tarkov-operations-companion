export function questItemPicture(id: string) {
  return QUEST_ITEM_PICTURES.has(id) ? `${import.meta.env.BASE_URL}quest-items/${id}.webp` : undefined
}

/** The catalog with its quest items' pictures (the same object when there is nothing to do). */
export function withQuestItemPictures<T extends { questItems?: Item[] }>(data: T): T {
  if (!data.questItems?.some((item) => !item.iconUrl && QUEST_ITEM_PICTURES.has(item.id))) return data
  return { ...data, questItems: data.questItems.map((item) => item.iconUrl ? item : { ...item, ...(questItemPicture(item.id) ? { iconUrl: questItemPicture(item.id) } : {}) }) }
}
