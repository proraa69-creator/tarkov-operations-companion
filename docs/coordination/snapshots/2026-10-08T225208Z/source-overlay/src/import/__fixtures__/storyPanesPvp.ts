/** The same panes with typical Tesseract slips: checkbox glyphs, «е» for «ё», a clipped first letter of the header. */
export function withOcrNoise(text: string) {
  return text
    .replace(/^Главные задачи$/m, 'лавные задачи')
    .replace(/^Опциональные задачи$/m, 'Опциональные задачи')
    .replace(/^(Поговорить|Разузнать|Узнать у|Починить|Найти оборудование|Найти личные|Найти памятный|Найти личный|Найти жетон|Посетить Лес)/gm, '[] $1')
    .replace(/ё/g, 'е')
}
